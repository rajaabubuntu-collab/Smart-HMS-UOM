// Synthetic examples only. This script never reads .env, connects to a database or sends mail.
import { mkdir, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import {
  appointmentEmailDetails,
  billingEmailDetails,
  snapshotEmail,
  renderEmail,
  securityEmail,
} from '../../server/src/notifications/email-content.js';

const directory = new URL('../../output/email-notifications/', import.meta.url);
await mkdir(directory, { recursive: true });
const origin = 'http://localhost:5173';
const id = 'aaaaaaaaaaaaaaaaaaaaaaaa';
const hospital = {
  name: 'Smart HMS',
  address: 'Colombo 09',
  phone: '+94 115 279 429',
  email: 'smarthms@gmail.com',
  isDemo: false,
};
const appointment = {
  reference: 'HMS-DEMO-001',
  startsAt: '2026-10-20T03:30:00Z',
  doctorName: 'Dr Demo Perera',
  departmentName: 'General Medicine',
  consultationFeeMinor: 250000,
  history: [{ fromStartsAt: '2026-10-19T09:00:00Z', fromDoctorName: 'Dr Demo Perera' }],
};
const bill = {
  reference: 'INV-DEMO-001',
  appointmentReference: appointment.reference,
  totalMinor: 350000,
  paidMinor: 200000,
  dueDate: '2026-10-25',
};
const payment = { reference: 'RCT-DEMO-001', amountMinor: 200000, method: 'Cash' };
const examples = {};
for (const kind of [
  'appointment_booked',
  'appointment_rescheduled',
  'appointment_cancelled',
  'appointment_checked_in',
  'appointment_reminder',
  'consultation_started',
  'consultation_completed',
  'prescription_updated',
  'bill_created',
  'bill_updated',
  'payment_recorded',
  'payment_reversed',
]) {
  const billing = kind.startsWith('bill_') || kind.startsWith('payment_');
  const details = billing
    ? billingEmailDetails(
        { ...bill, paidMinor: kind === 'payment_reversed' ? 0 : bill.paidMinor },
        kind,
        payment,
      )
    : appointmentEmailDetails(appointment, kind);
  examples[kind] = renderEmail(
    snapshotEmail(
      {
        email: details,
        path: billing
          ? `/billing/${id}`
          : kind === 'prescription_updated' || kind === 'consultation_completed'
            ? '/records'
            : `/appointments?selected=${id}`,
      },
      'Demo Patient',
      hospital,
      new Date('2026-10-14T04:00:00Z'),
    ),
    origin,
  );
}
// This fixed placeholder token is not issued by the system and cannot reset an account.
examples.password_reset = securityEmail('reset', origin, '0'.repeat(64), hospital);
examples.password_changed = securityEmail('changed', origin, undefined, hospital);

const browser = await chromium.launch({
  executablePath:
    process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH ||
    (existsSync('/usr/bin/google-chrome') ? '/usr/bin/google-chrome' : undefined),
});
try {
  const page = await browser.newPage();
  await page.route('**/*', (route) => route.abort());
  for (const [name, content] of Object.entries(examples)) {
    await writeFile(new URL(`${name}.html`, directory), content.html);
    await writeFile(
      new URL(`${name}.txt`, directory),
      `SYNTHETIC PREVIEW — no email sent\nSubject: ${content.subject}\n\n${content.text}\n`,
    );
    for (const width of [960, 390, 320]) {
      await page.setViewportSize({ width, height: 900 });
      await page.setContent(content.html);
      assert.equal(
        await page.evaluate(
          () => globalThis.document.documentElement.scrollWidth <= globalThis.innerWidth,
        ),
        true,
        `${name} overflow at ${width}px`,
      );
      assert.equal(await page.getByRole('heading', { level: 1 }).count(), 1);
      if (
        [
          'appointment_booked',
          'appointment_rescheduled',
          'payment_recorded',
          'password_reset',
        ].includes(name) &&
        width !== 320
      )
        await page.screenshot({
          path: fileURLToPath(new URL(`${name}-${width}.png`, directory)),
          fullPage: true,
        });
    }
  }
} finally {
  await browser.close();
}
await writeFile(
  new URL('README.md', directory),
  '# Synthetic email previews\n\nThese files contain fictional patients, appointments and payments. No email was sent. The reset token is a nonfunctional placeholder. Open an HTML file to inspect the layout; TXT files contain the subject and plain-text alternative. Portal links point to the local development app.\n\nGenerated by `node scripts/verification/email-previews.mjs`. Layout checked in Chromium at 960, 390 and 320 pixels; this is not a claim of rendering validation in every email client.\n',
);
console.log(
  `Created ${Object.keys(examples).length} synthetic email previews; all fit 960px, 390px and 320px viewports. No email sent.`,
);
